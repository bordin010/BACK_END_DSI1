// Object (Objetos)
// Um objeto agrupa várias informações dentro de uma mesma variável, usando chave e valor

let pessoa = {
    nome: "João",
    idade: 16,
    cidade: "São Paulo"
};

console.log(pessoa.nome);
console.log(pessoa.idade);


